type TranslationValue = string | TranslationTree

type TranslationTree = {
  [key: string]: TranslationValue
}

function isTranslationTree(value: unknown): value is TranslationTree {
  return typeof value === 'object' && value !== null && !Array.isArray(value)
}

function mergeTranslations<T extends TranslationTree>(
  base: T,
  overrides: TranslationTree
): T {
  const result: TranslationTree = { ...base }

  for (const [key, value] of Object.entries(overrides)) {
    const baseValue = result[key]

    if (isTranslationTree(baseValue) && isTranslationTree(value)) {
      result[key] = mergeTranslations(baseValue, value)
      continue
    }

    result[key] = value
  }

  return result as T
}

